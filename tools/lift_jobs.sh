#!/bin/zsh
# Lift the SPURS job binaries PES 2013 runs from its job chain.
#
#   tools/lift_jobs.sh
#
# A job binary is a raw image inside the EBOOT, not an SPU ELF, so lift_spu.sh does
# not find it. Without a lift a job runs in the SPU interpreter: fine for the short
# per-frame job, but a match queues up to 15 animation jobs of ~100k instructions
# each, which took the game down to ~14 updates a second.
#
# The guest addresses are the 1.04 EBOOT's. Its job binaries are byte-identical to
# the 1.00 ones (0x019B1800 and 0x019B7200), so the fingerprints did not move.
#
# Output: port/spu/job_<fingerprint>/spu_recomp.{c,h} (never commit: derived from
# game code) and port/spu/jobmods_register.c (fingerprints and names only).
set -e
here=${0:A:h}; source "$here/env.sh"
"$PY" - "$PES_ROOT" "$PS3RECOMP_DIR" "$PES_EBOOT" <<'PYEOF'
import os, struct, subprocess, sys
root, kit, eboot_path = sys.argv[1:4]
sys.path.insert(0, f"{kit}/tools")
from wrap_spu_elf import wrap
JOBS = [(0x01A0F380, 22944, "animation curves"), (0x01A14D80, 5312, "per-frame job")]
FIRST_IMAGE_ID = 10  # the EBOOT's SPU images are 1-9

eboot = open(eboot_path, "rb").read()
ph, phsize, phnum = struct.unpack(">Q", eboot[32:40])[0], *struct.unpack(">HH", eboot[54:58])
loads = [struct.unpack(">IIQQQQQQ", eboot[ph + i * phsize:ph + i * phsize + 56]) for i in range(phnum)]
def eboot_bytes(ea, size):
    for kind, _, off, va, _, filesz, _, _ in loads:
        if kind == 1 and va <= ea and ea + size <= va + filesz:
            return eboot[off + ea - va:off + ea - va + size]
    raise SystemExit(f"0x{ea:08X}+{size} is not in the EBOOT")
def fingerprint(data):  # spu_workload_fingerprint
    h = 1469598103934665603
    for b in data:
        h = ((h ^ b) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return f"{h:016X}"

spu = f"{root}/port/spu"
os.makedirs(f"{root}/cache", exist_ok=True)   # an installed copy starts without it
lifted = []
for ea, size, what in JOBS:
    data = eboot_bytes(ea, size)
    fp = fingerprint(data)
    prefix, out = f"job_{fp}_", f"{spu}/job_{fp}"
    elf = f"{root}/cache/job_{fp}.elf"
    # jm2 loads a job at LS 0 and enters it there (runtime/spu/spurs_job.c).
    open(elf, "wb").write(wrap(data, base=0, entry=0))
    subprocess.check_call([sys.executable, f"{kit}/tools/spu_lifter.py", "--auto-functions", elf,
        "--base", "0x0", "--symbol-prefix", prefix, "-o", out, "--merge-chunks",
        "--source-name", "spu_recomp.c", "--header-name", "spu_recomp.h"],
        stdout=subprocess.DEVNULL)
    os.remove(elf)
    lifted.append((fp, prefix))
    print(f"[lift_jobs] 0x{ea:08X}+{size} ({what}) -> job_{fp}")

with open(f"{spu}/jobmods_register.c", "w") as f:
    f.write("/* GENERATED by tools/lift_jobs.sh: the job binaries the chain dispatches. */\n")
    f.write('#include "spu_workload.h"\n')
    f.write("extern void spu_begin_image(int image_id);\n")
    for fp, prefix in lifted:
        f.write(f"extern void {prefix}spu_func_00000000(spu_context*);\n")
        f.write(f"extern void {prefix}spu_recomp_register(void);\n")
    f.write("__attribute__((constructor)) static void jobmods_register(void)\n{\n")
    for i, (fp, prefix) in enumerate(lifted):
        image = FIRST_IMAGE_ID + i
        f.write(f"    spu_begin_image({image}); {prefix}spu_recomp_register();\n")
        f.write(f"    spu_workload_register_img(0x{fp}ULL, {prefix}spu_func_00000000, {image}, "
                f'"job_{fp}");\n')
    f.write("    spu_begin_image(0);\n}\n")
PYEOF
