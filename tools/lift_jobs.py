#!/usr/bin/env python3
"""Lift the SPURS job binaries PES 2013 runs from its job chain.

    lift_jobs.py --toolkit DIR --eboot EBOOT.elf [--out DIR]

The same work as tools/lift_jobs.sh, in Python so the Windows build
(tools/windows/rebuild.ps1) runs it without zsh; see lift_jobs.sh for why the
jobs are lifted at all. Keep the JOBS table in step with it.

Output: port/spu/job_<fingerprint>/spu_recomp.{c,h} (never commit: derived from
game code) and port/spu/jobmods_register.c (fingerprints and names only).
"""
import argparse
import os
from pathlib import Path
import struct
import subprocess
import sys

# The 1.04 EBOOT's guest addresses (byte-identical to the 1.00 job binaries).
JOBS = [(0x01A0F380, 22944, "animation curves"), (0x01A14D80, 5312, "per-frame job")]
FIRST_IMAGE_ID = 10  # the EBOOT's SPU images are 1-9


def fingerprint(data):  # spu_workload_fingerprint
    h = 1469598103934665603
    for b in data:
        h = ((h ^ b) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return f"{h:016X}"


def main():
    root = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--toolkit", required=True)
    ap.add_argument("--eboot", required=True, help="the decrypted EBOOT.elf")
    ap.add_argument("--out", default=str(root / "port" / "spu"))
    a = ap.parse_args()
    kit = Path(a.toolkit) / "tools"
    sys.path.insert(0, str(kit))
    from wrap_spu_elf import wrap

    eboot = Path(a.eboot).read_bytes()
    ph = struct.unpack(">Q", eboot[32:40])[0]
    phsize, phnum = struct.unpack(">HH", eboot[54:58])
    loads = [struct.unpack(">IIQQQQQQ", eboot[ph + i * phsize:ph + i * phsize + 56]) for i in range(phnum)]

    def eboot_bytes(ea, size):
        for kind, _, off, va, _, filesz, _, _ in loads:
            if kind == 1 and va <= ea and ea + size <= va + filesz:
                return eboot[off + ea - va:off + ea - va + size]
        sys.exit(f"0x{ea:08X}+{size} is not in the EBOOT")

    spu = Path(a.out)
    cache = root / "cache"
    cache.mkdir(exist_ok=True)
    spu.mkdir(parents=True, exist_ok=True)
    lifted = []
    for ea, size, what in JOBS:
        data = eboot_bytes(ea, size)
        fp = fingerprint(data)
        prefix, out = f"job_{fp}_", spu / f"job_{fp}"
        elf = cache / f"job_{fp}.elf"
        # jm2 loads a job at LS 0 and enters it there (runtime/spu/spurs_job.c).
        elf.write_bytes(wrap(data, base=0, entry=0))
        subprocess.check_call([sys.executable, str(kit / "spu_lifter.py"), "--auto-functions", str(elf),
                               "--base", "0x0", "--symbol-prefix", prefix, "--output", str(out),
                               "--merge-chunks", "--source-name", "spu_recomp.c",
                               "--header-name", "spu_recomp.h"],
                              stdout=subprocess.DEVNULL)
        os.remove(elf)
        lifted.append((fp, prefix))
        print(f"[lift_jobs] 0x{ea:08X}+{size} ({what}) -> job_{fp}", flush=True)

    with open(spu / "jobmods_register.c", "w", newline="\n") as f:
        f.write("/* GENERATED by tools/lift_jobs.py: the job binaries the chain dispatches. */\n")
        f.write('#include "spu_workload.h"\n')
        f.write("extern void spu_begin_image(int image_id);\n")
        for fp, prefix in lifted:
            f.write(f"extern void {prefix}spu_func_00000000(spu_context*);\n")
            f.write(f"extern void {prefix}spu_recomp_register(void);\n")
        f.write("__attribute__((constructor)) static void jobmods_register(void)\n{\n")
        for i, (fp, prefix) in enumerate(lifted):
            image = FIRST_IMAGE_ID + i
            f.write(f"    spu_begin_image({image}); {prefix}spu_recomp_register();\n")
            f.write(f"    spu_workload_register_img(0x{fp}ULL, {prefix}spu_func_00000000, {image}, "
                    f'"job_{fp}");\n')
        f.write("    spu_begin_image(0);\n}\n")


if __name__ == "__main__":
    main()
